/** 返回事件类型的中文名。 */
export const kindName = (value: string) => kindNames[value] ?? value
/** 返回操作的中文名。 */
export const operationName = (value: string) =>
  operationNames[value] ??
  (value.startsWith("dns.")
    ? `DNS 查询 ${value.slice(4)}`
    : value.startsWith("fs.")
      ? `文件操作 ${value.slice(3)}`
      : value)
/** 返回函数的中文名。 */
export const functionName = (value: string) => functionNames[value] ?? value
